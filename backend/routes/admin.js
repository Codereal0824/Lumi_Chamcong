const router = require('express').Router();
const { requireAuth, requireRole } = require('../middleware/auth');
const controller = require('../controllers/adminController');
router.use(requireAuth, requireRole('admin'));
router.get('/attendances', controller.listAttendances);
router.put('/attendances/:id/status', controller.updateStatus);
router.get('/dashboard-stats', controller.dashboardStats);
router.get('/export-excel', controller.exportExcel);
router.get('/users', controller.listUsers);
router.post('/users', controller.createUser);
router.get('/users/:id', controller.getUser);
router.put('/users/:id', controller.updateUser);
router.get('/password-reset-requests', controller.listPasswordResetRequests);
router.get('/password-reset-requests/:id', controller.getPasswordResetRequest);
router.post('/password-reset-requests/:id/approve', controller.approvePasswordReset);
router.post('/password-reset-requests/:id/reject', controller.rejectPasswordReset);
router.post('/password-reset-requests/:id/resend-otp', controller.resendPasswordResetOtp);
router.get('/email/verify', controller.verifyEmailConfiguration);
router.post('/email/test', controller.sendEmailTest);
module.exports = router;
